def test_prediction_tool_is_routed_and_reported():
    """A prediction question must reach the tool and appear in the result."""

    class StubResult:
        prediction, probability, label = 1, 0.73, "repeat"
        features_used = {"first_order_revenue": 20.0}
        model_version, status, reason = "stub_v1", "success", ""

        def to_dict(self):
            return {"prediction": 1, "probability": 0.73, "label": "repeat",
                    "model_version": "stub_v1", "status": "success"}

    class StubTool:
        def __init__(self):
            self.seen = []

        def predict(self, customer_id=None, features=None):
            self.seen.append(customer_id)
            return StubResult()

    tool = StubTool()
    agent = AnalyticsAgent(llm=RuleBasedLLM(), prediction_tool=tool,
                           audit=NullAuditLogger(), cache_enabled=False)
    result = agent.run("Predict whether customer 12583 will make a repeat purchase")

    assert result["tools_used"] == ["prediction"]
    assert tool.seen == ["12583"]
    assert result["prediction"]["probability"] == 0.73


def test_template_sql_never_includes_cancelled_orders():
    """Every revenue template must keep the is_cancelled = 0 convention."""
    for question in ["what was total revenue in 2011", "monthly revenue",
                     "top 10 customers", "average order value",
                     "revenue by country", "high-value customers"]:
        sql = template_sql(question)
        assert sql is not None, question
        if "revenue" in sql.lower() and "order_items" in sql.lower():
            assert "is_cancelled = 0" in sql, question


def test_generated_sql_cannot_read_the_schema_catalogue():
    assert validate_sql("SELECT name, sql FROM sqlite_master")["allowed"] is False
    assert validate_sql("SELECT * FROM information_schema.tables")["allowed"] is False


def test_long_question_is_rejected_at_the_configured_limit():
    agent = AnalyticsAgent(llm=RuleBasedLLM(), audit=NullAuditLogger(),
                           cache_enabled=False, max_question_length=50)
    result = agent.run("revenue " * 40)
    assert result["status"] == "blocked"


def test_cache_returns_a_copy_not_the_live_result(retriever, sql_tool):
    """Mutating a returned result must not corrupt the cached entry."""
    agent = AnalyticsAgent(llm=RuleBasedLLM(), retriever=retriever,
                           sql_tool=sql_tool, audit=NullAuditLogger(),
                           cache_enabled=True)
    first = agent.run("What is Customer Lifetime Value?")
    first["sources"].append("injected-by-caller")

    second = agent.run("What is Customer Lifetime Value?")
    assert second["cached"] is True
    assert "injected-by-caller" not in second["sources"]


def test_sql_tool_result_contract_is_identical_on_every_branch(sql_tool):
    keys = {"status", "reason", "sql", "rows", "row_count", "columns",
            "truncated", "latency_ms"}
    for sql in ["SELECT SUM(revenue) AS r FROM transactions",  # success
                "DELETE FROM transactions",                     # blocked
                "SELECT * FROM does_not_exist"]:                # error
        assert keys <= set(sql_tool.execute(sql)), sql
