    result = sql_tool.execute(
        "SELECT SUM(revenue) AS total_revenue FROM transactions "
        "WHERE transaction_date LIKE '2011%'"
    )
    assert result["status"] == "success"
    assert result["rows"][0]["total_revenue"] == 55.0


